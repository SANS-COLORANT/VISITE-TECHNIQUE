import assert from 'node:assert/strict';
import { decouperRapportPdf, extraireEnteteRapport, composerHtmlFragment } from '../reportPdfFragments.js';
const datas=[{visite:{id:1},sections:[{panelId:'a'}],remarques:[{id:10}],materiel:[{id:20}]},{visite:{id:2},sections:[{panelId:'b'}],remarques:[],materiel:[]}];
const photos=Array.from({length:457},(_,i)=>({id:i,visiteId:i<300?1:2,ordre:i<300?i:i-300,include:true}));
const pieces=decouperRapportPdf(datas,photos);
assert.equal(pieces.length,Math.ceil(300/8)+Math.ceil(157/8));
assert.equal(pieces.reduce((n,x)=>n+x.photosConfig.length,0),457);
assert.ok(pieces.every(x=>x.photosConfig.length<=8));
assert.equal(pieces.filter(x=>x.data.sections.length).length,2);
assert.equal(pieces.filter(x=>x.data.remarques.length).length,1);
assert.equal(pieces.filter(x=>x.data.materiel.length).length,1);
const html='<!doctype html><html><head><style>ok</style></head><body><div class="cover">COUVERTURE</div><article class="siteReport"><div class="siteStart"><h1>SITE</h1></div><section class="photoPage pageBreakBefore">PHOTO</section></article><div class="sig">SIGNATURE</div></body></html>';
const head=extraireEnteteRapport(html);
assert.ok(head.includes('COUVERTURE'));
const first=composerHtmlFragment(html,head,{premierDocument:true,premierLocal:true,dernierLocal:false});
assert.equal((first.match(/COUVERTURE/g)||[]).length,1);
assert.equal((first.match(/SIGNATURE/g)||[]).length,0);
const middle=composerHtmlFragment(html,head,{premierDocument:false,premierLocal:false,dernierLocal:false});
assert.equal((middle.match(/COUVERTURE/g)||[]).length,0);
assert.equal((middle.match(/<h1>SITE/g)||[]).length,0);
const last=composerHtmlFragment(html,head,{premierDocument:false,premierLocal:false,dernierLocal:true});
assert.equal((last.match(/SIGNATURE/g)||[]).length,1);
console.log('PDF fragments: 457 photos, section/reserve/material single-pass, cover and signatures validated.');
