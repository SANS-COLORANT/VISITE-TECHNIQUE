/**
 * Secure, user-portable METRA backup (Android Google Play).
 *  - Password-protected AES-256 ZIP, all private visit/mission media directories.
 *  - Legacy v1 ZIP import requires explicit informed consent.
 *  - Validate paths, manifest, size and database integrity before changing data.
 *  - Local rollback snapshot retained if replacement or rollback fails.
 *
 * No password is written to SQLite, storage, telemetry or application logs.
 */
import * as FileSystem from 'expo-file-system/legacy';
import * as Sharing from 'expo-sharing';
import * as DocumentPicker from 'expo-document-picker';
import {
  zipWithPassword, unzipWithPassword, unzip, isPasswordProtected,
  listContents,
} from 'react-native-zip-archive';
import { getDb } from './db.js';
import { DATABASE_NAME, DATABASE_SCHEMA_VERSION } from './database/constants.js';
import { closeAppDatabase, openAppDatabase, verifyDatabaseIntegrity } from './database/index.js';
import { getSaveActivity } from './saveActivity.js';
import {
  BACKUP_FORMAT, BACKUP_FORMAT_VERSION, BACKUP_ENCRYPTION,
  BACKUP_MAX_UNCOMPRESSED_BYTES, validerMotDePasseSauvegarde,
  validerManifesteSauvegarde, validerEntreesZip,
} from './backupPolicy.js';

const ROOTS = Object.freeze(['visite-technique/', 'metra-missions/']);
const DATA_ROOT = 'data/';
const BACKUP_PREFIX = 'METRA_Chiffre_';
const PRIVATE_BACKUP_FOLDER = 'metra-encrypted-backups/';
let backupBusy = false;

const native = (uri) => String(uri || '').replace(/^file:\/\//, '');
const root = () => {
  if (!FileSystem.documentDirectory || !FileSystem.cacheDirectory) {
    throw new Error('Stockage privé Android indisponible.');
  }
  return FileSystem.documentDirectory;
};
const dbUri = () => root() + 'SQLite/' + DATABASE_NAME;
const exists = async (uri) => Boolean((await FileSystem.getInfoAsync(uri))?.exists);
const safeRemove = async (uri) => FileSystem.deleteAsync(uri, { idempotent: true }).catch(() => {});
const ensureDir = async (uri) => FileSystem.makeDirectoryAsync(uri, { intermediates: true });
const cleanDir = async (uri) => { await safeRemove(uri); await ensureDir(uri); };
function stamp() { return new Date().toISOString().replace(/[:.]/g, '-'); }
function requireIdle() {
  if (backupBusy) throw new Error('Une opération de sauvegarde ou de restauration est déjà en cours.');
  const s = getSaveActivity();
  if (s.pending > 0 || s.lastError) {
    throw new Error('Des champs ou photographies sont encore en cours d’enregistrement, ou un enregistrement a échoué. Finalise les saisies avant de sauvegarder.');
  }
}
async function requireSpace(requiredBytes) {
  let available = null;
  try { available = await FileSystem.getFreeDiskStorageAsync(); } catch {}
  if (Number.isFinite(available) && available < requiredBytes) {
    throw new Error('Espace libre insuffisant pour préparer et vérifier la sauvegarde/restauration. Libère du stockage sans supprimer les données METRA.');
  }
}
async function checkPhotos(db) {
  // All new visit photos are private app files and must physically exist.
  const rows = await db.getAllAsync('SELECT id, uri FROM photos');
  let missing = 0, outsideBackup = 0;
  const allowed = ROOTS.map(folder => root() + folder);
  for (const row of rows) {
    const uri = String(row.uri || '');
    if (!uri) { missing++; continue; }
    const managed = allowed.some(folder => uri.startsWith(folder));
    // Do not silently claim that gallery/cache/external photos are inside
    // a complete backup when the referenced bytes are outside owned roots.
    if (!managed && (/^file:\/\//.test(uri) || /^content:\/\//.test(uri))) {
      outsideBackup++;
      continue;
    }
    if (managed && !(await exists(uri))) missing++;
  }
  if (missing || outsideBackup) {
    throw new Error('Sauvegarde complète suspendue : ' + missing + ' photo(s) manquante(s), ' +
      outsideBackup + ' photo(s) référencée(s) hors des dossiers durables METRA. Ne supprime pas l’application. Fais d’abord diagnostiquer ou rapatrier ces fichiers.');
  }
  return rows.length;
}
async function countRows(db) {
  const [visites, photos] = await Promise.all([
    db.getFirstAsync('SELECT COUNT(*) AS n FROM visites'),
    db.getFirstAsync('SELECT COUNT(*) AS n FROM photos'),
  ]);
  return { visites: Number(visites?.n || 0), photos: Number(photos?.n || 0) };
}
async function checkpoint(db) { await db.execAsync('PRAGMA wal_checkpoint(TRUNCATE);'); }
/** SQLite's VACUUM INTO produces a consistent file snapshot even with WAL.
 * Do not copy the live .db: concurrent Intranet writes can still be in -wal.
 * The path is a private filename generated by METRA, bound as an SQL parameter.
 */
async function snapshotDatabase(db, destination) {
  await safeRemove(destination);
  await db.runAsync('VACUUM INTO ?', [native(destination)]);
  const info = await FileSystem.getInfoAsync(destination, { size: true });
  if (!info?.exists || Number(info.size || 0) < 1024) {
    throw new Error('Snapshot SQLite incomplet : aucune sauvegarde ne sera diffusée.');
  }
}
async function cleanJournals(base) {
  for (const suffix of ['-wal', '-shm', '-journal']) await safeRemove(base + suffix);
}
async function copyRoots(from, to) {
  for (const name of ROOTS) {
    if (await exists(from + name)) await FileSystem.copyAsync({ from: from + name, to: to + name });
    else await ensureDir(to + name);
  }
}
async function checkNativeEncryptedArchive(uri) {
  if (!(await isPasswordProtected(native(uri)))) throw new Error('Le ZIP exporté n’est pas protégé par un mot de passe : export annulé.');
  const entries = await listContents(native(uri));
  const total = validerEntreesZip(entries);
  const files = entries.filter(item => !item.isDirectory);
  if (!files.length || files.some(item => !item.isEncrypted)) {
    throw new Error('Au moins un fichier de la sauvegarde ZIP n’est pas chiffré.');
  }
  return total;
}

/** Export AES-256 with an explicit user passphrase. Never create a plain ZIP. */
export async function exporterSauvegardeChiffree({ motDePasse } = {}) {
  const password = validerMotDePasseSauvegarde(motDePasse);
  requireIdle();
  backupBusy = true;
  const id = stamp();
  const travail = FileSystem.cacheDirectory + 'metra-backup-work-' + id + '/';
  const archive = root() + PRIVATE_BACKUP_FOLDER + BACKUP_PREFIX + id + '.zip';
  let archiveValide = false;
  try {
    const db = await getDb();
    const integrity = await verifyDatabaseIntegrity(db);
    if (!integrity.integrityOk || !integrity.foreignKeysOk) throw new Error('SQLite n’est pas intègre. Sauvegarde refusée pour éviter une copie corrompue.');
    await checkPhotos(db);
    const source = dbUri();
    const info = await FileSystem.getInfoAsync(source, { size: true });
    if (!info?.exists || Number(info?.size || 0) <= 0) throw new Error('Base SQLite source introuvable.');
    await requireSpace(Number(info.size) * 3 + 64 * 1024 * 1024);
    await cleanDir(travail);
    await ensureDir(travail + 'database/');
    await ensureDir(travail + DATA_ROOT);
    await snapshotDatabase(db, travail + 'database/' + DATABASE_NAME);
    await copyRoots(root(), travail + DATA_ROOT);

    const counts = await countRows(db);
    const manifeste = {
      format: BACKUP_FORMAT,
      formatVersion: BACKUP_FORMAT_VERSION,
      schemaVersion: DATABASE_SCHEMA_VERSION,
      createdAt: new Date().toISOString(),
      database: 'database/' + DATABASE_NAME,
      photosRoot: DATA_ROOT + 'visite-technique/photos/',
      dataRoots: ROOTS.map(folder => DATA_ROOT + folder),
      counts,
      encryption: BACKUP_ENCRYPTION,
    };
    validerManifesteSauvegarde(manifeste, DATABASE_NAME, DATABASE_SCHEMA_VERSION);
    await FileSystem.writeAsStringAsync(travail + 'manifest.json', JSON.stringify(manifeste));
    await ensureDir(root() + PRIVATE_BACKUP_FOLDER);
    await safeRemove(archive);
    await zipWithPassword(native(travail), native(archive), password, BACKUP_ENCRYPTION);
    await checkNativeEncryptedArchive(archive);
    archiveValide = true; // Garder cette copie chiffrée durable pour un nouveau partage.
    if (!(await Sharing.isAvailableAsync())) throw new Error('Le partage des fichiers est indisponible sur cet appareil.');
    await Sharing.shareAsync(archive, { mimeType: 'application/zip', dialogTitle: 'Enregistrer la sauvegarde chiffrée METRA' });
    return { manifeste, nom: archive.split('/').pop(), uri: archive, partage: true, encryption: BACKUP_ENCRYPTION, savedLocally: true };
  } finally {
    await safeRemove(travail);
    if (!archiveValide) await safeRemove(archive);
    backupBusy = false;
  }
}

/** Android Sharesheet may outlive the call. Keep the verified encrypted ZIP
 * private and allow users to share again without recreating the archive.
 */
export async function partagerDerniereSauvegardeChiffree() {
  if (backupBusy) throw new Error('Une sauvegarde est en cours, réessaie après sa fin.');
  const folder = root() + PRIVATE_BACKUP_FOLDER;
  const info = await FileSystem.getInfoAsync(folder);
  if (!info?.exists) throw new Error('Aucune sauvegarde chiffrée locale à partager.');
  const files = (await FileSystem.readDirectoryAsync(folder))
    .filter(name => name.startsWith(BACKUP_PREFIX) && name.endsWith('.zip'))
    .sort().reverse();
  for (const name of files) {
    const uri = folder + name;
    if (!(await exists(uri))) continue;
    await checkNativeEncryptedArchive(uri);
    if (!(await Sharing.isAvailableAsync())) throw new Error('Le partage Android est indisponible.');
    await Sharing.shareAsync(uri, { mimeType: 'application/zip', dialogTitle: 'Enregistrer la sauvegarde METRA hors du téléphone' });
    return { nom: name, uri, partage: true };
  }
  throw new Error('Aucune archive chiffrée valide à partager.');
}
async function inspectArchive(uri, { motDePasse, autoriserArchiveAncienne }) {
  const entries = await listContents(native(uri));
  const total = validerEntreesZip(entries);
  const encrypted = await isPasswordProtected(native(uri));
  const files = entries.filter(e => !e.isDirectory);
  if (encrypted) {
    if (files.some(e => !e.isEncrypted)) throw new Error('Archive partiellement chiffrée : restauration refusée.');
    validerMotDePasseSauvegarde(motDePasse);
  } else if (!autoriserArchiveAncienne) {
    throw new Error('Cette archive ZIP n’est pas chiffrée. Active explicitement l’option « Ancienne sauvegarde non chiffrée » pour l’importer.');
  }
  if (total > BACKUP_MAX_UNCOMPRESSED_BYTES) throw new Error('Sauvegarde trop volumineuse.');
  await requireSpace(Math.ceil(total * 2.2) + 64 * 1024 * 1024);
  return { encrypted, total };
}
async function validateRestoredContent(unpacked, encrypted) {
  const manifestUri = unpacked + 'manifest.json';
  if (!(await exists(manifestUri))) throw new Error('Manifeste METRA absent du ZIP.');
  const manifeste = JSON.parse(await FileSystem.readAsStringAsync(manifestUri));
  const policy = validerManifesteSauvegarde(manifeste, DATABASE_NAME, DATABASE_SCHEMA_VERSION);
  if (policy.formatVersion === 2 && !encrypted) throw new Error('Une sauvegarde METRA version 2 doit être entièrement chiffrée.');
  const restoredDatabase = unpacked + policy.dbPath;
  const sourceInfo = await FileSystem.getInfoAsync(restoredDatabase, { size: true });
  if (!sourceInfo?.exists || Number(sourceInfo.size || 0) < 1024) throw new Error('Base SQLite manquante ou trop petite dans le ZIP.');
  if (policy.formatVersion === 2) {
    for (const folder of ROOTS) {
      if (!(await exists(unpacked + DATA_ROOT + folder))) {
        throw new Error('La sauvegarde complète ne contient pas le dossier ' + folder);
      }
    }
  }
  return { manifeste, policy, restoredDatabase };
}
const safeSqlId = (id) => '"' + String(id).replace(/"/g, '""') + '"';
async function rebaseKnownFileUris(db) {
  const map = {
    photos: ['uri'],
    api_latest_visit_photos: ['local_uri'],
    api_photo_files: ['local_uri'],
    mission_photos: ['file_uri', 'preview_uri', 'thumbnail_uri'],
    mission_documents: ['file_uri'],
    mission_map_layers: ['source_uri'],
  };
  for (const [table, columns] of Object.entries(map)) {
    const existsTable = await db.getFirstAsync("SELECT name FROM sqlite_master WHERE type='table' AND name=?", [table]);
    if (!existsTable) continue;
    const cols = new Set((await db.getAllAsync('PRAGMA table_info(' + safeSqlId(table) + ')')).map(r => r.name));
    for (const col of columns) {
      if (!cols.has(col)) continue;
      const identifier = safeSqlId(col), name = safeSqlId(table);
      for (const folder of ROOTS) {
        const marker = '/' + folder;
        await db.runAsync(
          'UPDATE ' + name + ' SET ' + identifier + ' = ? || substr(' + identifier +
            ', instr(' + identifier + ', ?) + length(?)) WHERE instr(' + identifier + ', ?) > 0',
          [root() + folder, marker, marker, marker]
        );
      }
    }
  }
}
async function assertPhotoIntegrity(db, expected) {
  const counts = await countRows(db);
  if (counts.visites !== expected.visites || counts.photos !== expected.photos) {
    throw new Error('Les nombres de visites/photos restaurés ne correspondent pas au manifeste.');
  }
  await checkPhotos(db);
}

/** Import AES-256 archives and explicitly authorized legacy plaintext v1 archives. */
export async function choisirEtRestaurerSauvegardeChiffree({ motDePasse = '', autoriserArchiveAncienne = false } = {}) {
  requireIdle();
  backupBusy = true;
  const id = stamp();
  const extracted = FileSystem.cacheDirectory + 'metra-restore-work-' + id + '/';
  const safety = root() + 'metra-restore-rollback-' + id + '/';
  let copiedSafety = false, replaced = false, rollbackSucceeded = false;
  try {
    const selection = await DocumentPicker.getDocumentAsync({
      type: ['application/zip', 'application/octet-stream', '*/*'],
      copyToCacheDirectory: true,
      multiple: false,
    });
    if (selection.canceled) return null;
    const asset = selection.assets?.[0];
    if (!asset?.uri) throw new Error('Fichier ZIP non sélectionné.');
    const scan = await inspectArchive(asset.uri, { motDePasse, autoriserArchiveAncienne });
    await cleanDir(extracted);
    try {
      if (scan.encrypted) await unzipWithPassword(native(asset.uri), native(extracted), motDePasse);
      else await unzip(native(asset.uri), native(extracted));
    } catch (error) {
      if (scan.encrypted) throw new Error('Déchiffrement impossible. Vérifie le mot de passe ou l’intégrité du ZIP. ' + String(error?.message || ''));
      throw error;
    }
    const { manifeste, policy, restoredDatabase } = await validateRestoredContent(extracted, scan.encrypted);
    const db = await getDb();
    const currentDb = dbUri();
    if (!(await exists(currentDb))) throw new Error('Base actuelle introuvable : restauration annulée.');
    await cleanDir(safety);
    await ensureDir(safety + 'database/');
    await snapshotDatabase(db, safety + 'database/' + DATABASE_NAME);
    // For legacy v1, preserve directories not backed up by the original app.
    await copyRoots(root(), safety);
    copiedSafety = true;

    await closeAppDatabase();
    replaced = true;
    await cleanJournals(currentDb);
    await FileSystem.copyAsync({ from: restoredDatabase, to: currentDb });
    if (policy.formatVersion === 1) {
      const previousPhotos = root() + 'visite-technique/photos/';
      await safeRemove(previousPhotos);
      if (await exists(extracted + 'photos/')) await FileSystem.copyAsync({ from: extracted + 'photos/', to: previousPhotos });
      else await ensureDir(previousPhotos);
    } else {
      for (const name of ROOTS) {
        await safeRemove(root() + name);
        await FileSystem.copyAsync({ from: extracted + DATA_ROOT + name, to: root() + name });
      }
    }
    const restoredDb = await openAppDatabase();
    await rebaseKnownFileUris(restoredDb);
    const verification = await verifyDatabaseIntegrity(restoredDb);
    if (!verification.integrityOk || !verification.foreignKeysOk) {
      throw new Error('La base restaurée n’a pas passé la vérification SQLite.');
    }
    await assertPhotoIntegrity(restoredDb, policy);
    await checkpoint(restoredDb);
    await closeAppDatabase();
    await cleanJournals(currentDb);
    await safeRemove(safety);
    copiedSafety = false;
    return { manifeste, controle: verification, restartRequired: true, encryption: scan.encrypted ? BACKUP_ENCRYPTION : 'legacy' };
  } catch (error) {
    if (replaced && copiedSafety) {
      try {
        await closeAppDatabase();
        const currentDb = dbUri();
        await cleanJournals(currentDb);
        await FileSystem.copyAsync({ from: safety + 'database/' + DATABASE_NAME, to: currentDb });
        for (const name of ROOTS) {
          await safeRemove(root() + name);
          await FileSystem.copyAsync({ from: safety + name, to: root() + name });
        }
        rollbackSucceeded = true;
        await safeRemove(safety);
      } catch (rollbackError) {
        console.error('[METRA backup] Restauration de sécurité impossible, copie privée conservée.', rollbackError?.message);
      }
      error.restoreTouchedDatabase = true;
      if (!rollbackSucceeded) {
        throw new Error('Échec de la restauration et de son retour arrière. N’efface pas METRA : une copie de sécurité est conservée dans le stockage privé de l’application. Contacte le support avant toute manipulation.');
      }
    }
    throw error;
  } finally {
    await safeRemove(extracted);
    if (!copiedSafety || rollbackSucceeded) await safeRemove(safety);
    backupBusy = false;
  }
}
